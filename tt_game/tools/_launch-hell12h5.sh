#!/usr/bin/env bash
# =====================================================================
#  _launch-hell12h5.sh — 第五轮 12h。与前三轮的根本区别：
#    **这一轮不再指望网络自己学会横向追球**，而是先把追球交给规则（lateral prior），
#    再让 TD 只去修剩下的弱项。
#
#  第四轮（input3-hell12h3）为什么白跑
#  -----------------------------------
#  跑满 12h（43553s < 43200s 预算略超，ep 10500），闸门 B 判负，未烘焙。
#  但曲线本身就说明问题：train 胜率 50.4% → 21.6% **单调下滑 10500 个 epoch**，
#  best 只在 ep2250 动过一次，此后 8300 个 epoch 再没动过。
#  逐轮实机复盘输因（tools/logs/input3-hell12h3.chain.log）：
#    ckpt-009500  default 22.8 / hell 3.0   失球：发球 67.5%、够不到 31.8%
#    ckpt-009750  default 32.0 / hell 2.7   失球：**够不到 99.5%**
#    best-002250  default 38.6 / hell 5.0   失球：**够不到 95.4%**、出界 4.6%
#  「够不到 95~99%」不是学习率问题，是**策略压根不横向追球**。
#
#  实测证据（tools/logs/_diag_argmax.txt，扫 13 个来球 x）
#  ---------------------------------------------------------
#  线上权重面对 x = −1.2…+1.2 的来球，只用到 **34 个鼠标X 档位里的 4 个**：
#    x ∈ [−0.8, +0.6] 时 tx 恒在 **±0.14 m** 以内，x ≥ +0.8 才猛打 +0.9，
#    x = −1.2 都**不去** −0.9。d(tx)/d(x) 回归斜率只有 0.421。
#  而触球窗口是 |球x − 拍x| ≤ PAD_HW 0.10 + BALL_R 0.02 + fitH 0.17…0.22 ≈ 0.29…0.34 m，
#  地狱 AI 把球放在 |x| ≈ 0.8…1.2 —— **物理上够不到**。
#  拍速不是瓶颈：MOUSE_PACE=18 @60Hz 每帧收敛残差的 30%（τ≈0.056s），
#  全场横移只要 0.15s。**问题不是手慢，是瞄错了地方。**
#
#  两个真·代码缺陷（已修，见 js/input-agent.js）
#  ---------------------------------------------
#  ① tauS 的判据方向反了。`vz < -0.05 && pz - z > 0` 只在球**离开**球拍时成立，
#     于是「该接球」的那几十帧里 τ≡0、预测落点三个特征全退化成当前位置 ——
#     网络没有任何前瞻信息。改成 `(pz-z)*vz > 0 && |vz| > 0.05`
#     （球正朝拍面来才算）。
#  ② 在线 BC 的目标物是**当前**球心 x（滞后量）。改成追**拦截预测点**
#     `x + vx·τ`。顺带修掉 BC 的三个问题：`Math.max(4, …)` 让 `--bcmix 0`
#     根本关不掉 BC（每 batch 固定 6.25%，12h 约 7.2 万次「把所有其他动作往 0 拉」）；
#     硬目标把全网往全零收敛；改成 raise-only。
#
#  实测收益（tools/live-match.js 新增 --brain，脚本脑直接接管决策）
#  ---------------------------------------------------------------
#    centre  tx ≡ 0            实机地狱胜率  0.4%   够不到 99.6%
#    naive   tx = 当前球心       实机地狱胜率 22.8%   够不到 93.8%
#    chase   tx = x + vx·τ      实机地狱胜率 40.1%   够不到 47.5% / 出界 52.5%
#    线上 DQN（第四轮之前的基线）  实机地狱胜率 11.7%
#  结论：**一行拦截预测点，零训练，+28.4pp（3.4 倍）**。
#
#  --brain prior = 保留网络自己的 my / ctrl / 上旋，只把横向 mxI 换成拦截预测点
#    → 实机地狱 **32.1%**（网络仍负责深度/旋转，故略低于纯脚本脑的 40.1%）。
#    这套逻辑已经落进 js/input-agent.js 的 bestAction()（默认开，
#    `agent.setLateralPrior(false)` 是回滚开关），训练与实机走**同一份代码**。
#  ⇒ 本轮 12h 的职责变得清晰且可验证：**修剩下的「出界」**（占追球后失球的 52.5%），
#    横向这一项已经由规则兜底，不需要网络再学一遍。
#
#  BC 预训练已证伪，不再走这条路
#  ------------------------------
#  试过 `--pool 120` 的监督暖启动：argmax 命中率只有 3.3%~10%，
#  实机地狱胜率 **0.0%**（把原策略打乱了）。1904 维输出上的 MSE 硬目标
#  是个全局下沉井（N 个状态把每行往下踩 N 次、往上推 N/65 次）。
#  imitate() 已改成**成对排序**更新（只抬示范 + 只压当前亚军），命中率能爬升，
#  但仍远不足以替代规则 —— 所以本轮 `--bcmix 0`，追球交给 prior，
#  BC 不要再去和 TD 抢 my / ctrl。
#
#  其余沿用第四轮（已验证有效）
#  ----------------------------
#  · 起点 data/checkpoints/input3-12h/ckpt-008500.json（= 生产权重）
#  · --lr0/--lr1 1e-5（强起点不能用来头训练的学习率，否则自己把自己练坏）
#  · --sel-ref hell（选优分必须真的指向地狱：0.75*地狱 + 0.25*默认护栏）
#  · 课程 default:0.25 → hell:0.45 → grandslam:0.15 → hell:0.15
#    （地狱累计 60% 但拆两段；default 提到 25% 当护栏）
#  · adam + grad-clip 2 + layer-lr 1,1,1,3
#    （**裸 SGD 会让 1904×192 输出层直接发散到 1e90+**，实测；这是历史上每次
#      训练都必须开 adam 的真实原因）
#  · --no-save：12 小时内绝不碰生产权重 js/input-weights.js
#  停止：touch data/.stop/input3-hell12h5.sup
# =====================================================================
set -u
cd "$(dirname "$0")/.." || exit 1
mkdir -p data/checkpoints/input3-hell12h5 tools/logs data/.stop

# ★ 2026-10-14 04:05：--games 9000 → 3200，并放宽卡死阈值。
# 第一轮跑出来的真实节奏（tools/logs/input3-hell12h5.log）：
#   ep 250 [default] train=76% vsdefault=98.3% vshell=85.0% vsgrandslam=98.3%
#            best=94.1@0 eps=0.18 剩11h25m  [2084s 训练 + 985s 验证]
# 一轮 = 3069s ≈ **51 分钟**（训练 250 局 2084s + 三档验证 90 局 985s）。
# 比第四轮慢一倍多，是因为**这一轮球真的被接住了**：以前 95% 的失球是
# 「够不到」，球落地极快；现在回合变长 → 每局帧数变多 → TD 更新次数变多。
#   ⇒ 按 elapsedSec（只算训练）43200s 最多买 20 轮 = 5000 局；
#     按墙钟 43200s 只买得到 **14 轮 = 3500 局**。
#
# 而课程边界是 `phase.to * opt.games`（train-input3.js L166/L979）。
# --games 9000 ⇒ default 段 = 前 2250 局 = **前 9 轮 ≈ 7.6 小时**；
# default 已在 98.3%，在这一档再烧 7.6 小时学不到东西，真正要修的地狱
# 只剩 4.4 小时。这不是训练强度问题，是**预算分配问题**。
#   ⇒ --games 3200 = 12.8 轮，约 11.1 小时墙钟，训练器自己收尾：
#       default 0-800（3.2 轮，护栏）→ hell 800-2240（5.8 轮，主战场）
#       → grandslam 2240-2720（1.9 轮）→ hell 2720-3200（1.9 轮）
#     地狱累计 60% ≈ 7.7 小时，其中约 3/4 在主战场而不是尾段。
#
# 同一批数据还暴露了守护的一个误判窗口：卡死判定数的是
# 「index.json 的 elapsedSec 连续 N 次轮询没变」，而 index.json
# **每个检查点（= 每轮）才重写一次**。一轮 51 分钟 > 旧的 SUP_STALL 1800s
# （30 分钟），于是**一个健康的训练器会被判成卡死并被杀**（首轮实测：
# 04:11 就会触发）。
#   ⇒ SUP_BOOT 3600（启动豁免 60 分钟）+ SUP_STALL 5400（静默 90 分钟才判死），
#     都严格大于实测的一轮耗时 3069s。

# 卡死阈值必须大于一轮实测耗时，否则会把健康的训练器杀掉。
export SUP_BOOT="${SUP_BOOT:-3600}"
export SUP_STALL="${SUP_STALL:-5400}"

exec bash tools/_supervise.sh input3-hell12h5 12 \
  data/checkpoints/input3-12h/ckpt-008500.json \
  --run-name input3-hell12h5 \
  --end hell \
  --sel-ref hell \
  --games 3200 \
  --step 250 \
  --eval 30 \
  --vallevels default,hell,grandslam \
  --ckpt 250 \
  --keep 16 \
  --no-save \
  --optimizer adam \
  --layer-lr 1,1,1,3 \
  --grad-clip 2 \
  --lr0 0.00001 \
  --lr1 0.00001 \
  --eps-reset 500 \
  --bcmix 0 \
  --curve data/checkpoints/input3-hell12h5/curve.json \
  --phases 'default:0.25,hell:0.45,grandslam:0.15,hell:0.15'