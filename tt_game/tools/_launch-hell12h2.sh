#!/usr/bin/env bash
# =====================================================================
#  _launch-hell12h2.sh — 第三轮 12h：把上一轮真正缺的东西补上
#
#  上一轮（input3-hell12h）的结果
#  ---------------------------
#  跑满 12h（43612s > 43200s 预算），ep 8300。收尾闸门 B 判负：
#  实机 vs 地狱 2.6% vs 基线 11.7%（−9.1pp），**未烘焙**，
#  js/input-weights.js 保持原样（md5 未变）——这是正确的安全结果。
#
#  失败复盘（详见 tools/phase4-findings.md §4b）
#  --------------------------------------------
#  ① **验证开销吃掉了训练时间**（本轮真正的首要原因）
#     `--eval 77` 让每轮验证从 ~160s 涨到 ~630s，占每轮 1430s 的 **38%**。
#     结果 12h 只跑到 ep8300，地狱段（ep6000~8300）实际只有 **2300 局**，
#     是 50% 预算计划的 **38%** —— 名义上「一半预算给地狱」，实际只拿到三分之一。
#     而且 ep7250~8250 四个 77 局点的地狱读数是 11.0 / 20.1 / 9.1 / 14.9，
#     彼此的差都在 ±3.4pp 标准误内，**读不出趋势**。
#     权衡：评估局数太少会看不见进步，太多就没时间训练。上一轮两头都没做好
#     ——38% 的时间花在读一个读不出趋势的数上。降到 40 局（±5.7pp），
#     验证占比回落到 24%，把省下的时间变成真实的对地狱训练量。
#
#  ② **早停误杀**（已修，见 train-input3.js）
#     早停判据写成 `abDrop || abFloor`，与注释「两条都满足才算退化」矛盾，
#     导致 ep2250 被误停（那三轮 default 是 30.0/27.5/30.0%，远高于 12% 地板，
#     只是分数相对峰值掉了 30%+，纯噪声）。已改成 `&&`。
#
#  ③ **深度旋钮不是问题**（已证伪，别再往这个方向试）
#     实测 `_diag_depth.js`：my 众数 0.462、84% 集中在该处、94.6% 偏前。
#     真正一样的是 **tx 均值 0.12**（中位是 0）——横向几乎不跟球。
#     「够不到球」是横向追踪问题，不是深度问题。
#
#  本轮课程：default:0.10 → extreme-max:0.10 → grandslam:0.10 → hell:0.70
#    · hell 提到 **70%**（上一轮 50%），且继续放最后不被后续阶段覆盖。
#      上一轮名义 50% 只落地 38%，这轮给它 70% 名义预算来对冲同样的损耗。
#    · default 10%：守住收尾闸门「vs普通 不劣于基线」要用的那一档。
#    · extreme-max / grandslam 各 10%（上一轮合计 40%）：它们只是别把已经
#      很强的那档训塌，不需要再花 40% 时间。grandslam 仍是实机真实可选对手，
#      收尾闸门给它 0.45 权重，所以保留 10% 足以不退化。
#
#  --eval 40（从 77 降下来）：见 ①。40 局/档对应地狱档 ±5.7pp 标准误，
#  是 10pp 级变化的最低可分辨门槛（phase3 §5.0 的方法论：任何 ≤10pp 的判断
#  至少要 20 局/档，这里留 2 倍余量）。配 --step 250，每 250 局一个采样点。
#
#  --games 9000：按实测吞吐（训练 3.21 s/局 + 每轮 40×4=160 局验证约 256s，
#    每轮 1058s），12h 约能跑 41 轮 ≈ 10200 局。写 9000 让课程四段在预算内
#    刚好走完（ep9000），不会像上一轮那样预算耗尽时第四段还没收尾。
#    分段：default 0-900 / extreme-max 900-1800 / grandslam 1800-2700 /
#          hell 2700-9000 —— **hell 段约 6300 局，是上一轮实际拿到 2300 局的 2.7 倍**。
#
#  起点：上一轮的最终权重（ckpt-007000，ep7000 选出的那份）。
#    为什么不是 ep8300 的检查点：所有检查点都是 bestNet 的副本（见 findings #21），
#    实际只有一份不同权重，ep8300 那份就是它。
#    它的 default 72.7% / hell 6.5% 仿真分，是目前手上最好的起点。
#
#  --no-save：12 小时内绝不碰生产权重 js/input-weights.js。
#  --run-name 每次都传（含续训），否则检查点会被另开到 <旧名>-<日期>，
#    守护读到的就是一份永不更新的死索引（phase3 §14）。
#
#  停止：touch data/.stop/input3-hell12h2.sup
# =====================================================================
set -u
cd "$(dirname "$0")/.." || exit 1
mkdir -p data/checkpoints/input3-hell12h2 tools/logs data/.stop

exec bash tools/_supervise.sh input3-hell12h2 12 \
  data/checkpoints/input3-hell12h/ckpt-007000.json \
  --run-name input3-hell12h2 \
  --end hell \
  --games 9000 \
  --step 250 \
  --eval 40 \
  --vallevels default,hell,grandslam,extreme-max \
  --ckpt 100 \
  --keep 16 \
  --no-save \
  --optimizer adam \
  --layer-lr 1,1,1,3 \
  --grad-clip 2 \
  --eps-reset 500 \
  --curve data/checkpoints/input3-hell12h2/curve.json \
  --phases 'default:0.10,extreme-max:0.10,grandslam:0.10,hell:0.70'